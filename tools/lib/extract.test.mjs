test('النصّان المتطابقان تكرار', () => {
  const a = fingerprint('ما بين بيتي ومنبري روضة من رياض الجنة.');
  assert.ok(sameText(a, a));
});

test('النصّ الذي هو مطلعُ نصٍّ أطول تكرار', () => {
  // البخاري ١١٩٥ و١١٩٦: متنٌ واحد، وإحدى الروايتين تزيد في آخرها.
  const short = fingerprint('ما بين بيتي ومنبري روضة من رياض الجنة.');
  const long = fingerprint('ما بين بيتي ومنبري روضة من رياض الجنة، ومنبري على حوضي.');
  assert.ok(sameText(short, long));
  assert.ok(sameText(long, short), 'الترتيب يؤثّر في الحكم');
});

test('النصّان المختلفان ليسا تكراراً', () => {
  const a = fingerprint('من صام رمضان إيماناً واحتساباً غفر له ما تقدم من ذنبه.');
  const b = fingerprint('من قام ليلة القدر إيماناً واحتساباً غفر له ما تقدم من ذنبه.');
  assert.ok(!sameText(a, b));
});

test('اتفاق كلماتٍ قليلة ليس تكراراً', () => {
  assert.ok(!sameText(fingerprint('من صام يوما'), fingerprint('من صام يوما في سبيل الله بعد الله وجهه')));
});

test('المفترقان في وسطهما تكرار — والمطلعُ يكشفهما', () => {
  // خبرٌ واحدٌ عن صالحٍ في كتابَي سِيَر، بفرق حرفٍ في وسطه: «تبين» و«تتبين».
  // فليس واحدهما مطلعَ الآخر، والبادئة لا تكشفه — وقد وصل المستخدمَ نصّان
  // متشابهان من «الحلية» و«صفة الصفوة» حتى كُشفا.
  const a = fingerprint('كان محمد بن النضر إذا ذكر الموت اضطربت مفاصله حتى تبين الرعدة فيها.');
  const b = fingerprint('كان محمد بن النضر إذا ذكر الموت اضطربت مفاصله حتى تتبين الرعدة فيها.');
  assert.ok(sameText(a, b));
  assert.ok(sameText(b, a), 'الترتيب يؤثّر في الحكم');
});

test('الزيادةُ في وسط الخبر لا تجعله جديداً', () => {
  // «فيذكر الله» و«فيذكر الله عز وجل» — والباقي سواء.
  const a = fingerprint('كان حسان بن عطية يتنحى إذا صلى العصر في ناحية المسجد، فيذكر الله عز وجل حتى تغيب الشمس.');
  const b = fingerprint('كان حسان بن عطية يتنحى إذا صلى العصر في ناحية المسجد فيذكر الله حتى تغيب الشمس.');
  assert.ok(sameText(a, b));
});

test('المطلعُ المشترك لا يُسقِط خبرين مختلفين', () => {
  // القاعدةُ على المطلع، فلا تُسقِط ما افترق **داخله**: صالحٌ آخر، أو عملٌ آخر.
  // وإلّا ضاع خبرٌ صحيحٌ لأجل مشابهةٍ في صدره.
  const sameManDifferentDeed = [
    fingerprint('كان الحسن البصري إذا ذكر الموت بكى حتى يغلبه النوم من طول القيام.'),
    fingerprint('كان الحسن البصري إذا ذكر الجنة اشتاق إليها وأكثر من الدعاء بها.'),
  ];
  assert.ok(!sameText(...sameManDifferentDeed));
  const sameDeedDifferentMan = [
    fingerprint('كان أبو بكر الصديق يقوم الليل ويصوم النهار ويتصدق بماله كله.'),
    fingerprint('كان عمر بن الخطاب يقوم الليل ويصوم النهار ويتصدق بماله كله.'),
  ];
  assert.ok(!sameText(...sameDeedDifferentMan));
});

