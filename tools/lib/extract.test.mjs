test('الحكمةُ تبتدئ باسمٍ أو فعل، لا بواوٍ ولا فاء', () => {
  // قِيس على ما قبله صاحب المشروع وما ردّه — فصلٌ تامٌّ أربعةَ عشرَ من أربعةَ عشر.
  const liked = [
    'العلم نورٌ يقذفه الله في القلب، والمعصية تُطفئ ذلك النور العظيم فلا يبقى.',
    'التوكل نصف الدين، والنصف الثاني: الإنابة؛ فإن الدين استعانةٌ وعبادة لله.',
    'الشكر: ظهور أثر نعمة الله على لسان عبده ثناءً واعترافاً، وعلى قلبه شهوداً.',
  ];
  const rejected = [
    'وقد أشار سبحانه إلى هذا في كتابه عند ذكر عقوبات الذنوب وأنه أركس أربابَها.',
    'وفي هذه المنزلة يحتاج إلى تمييز ما له ممّا عليه، ليستصحِبَ ما له ويؤدّيَ ما عليه.',
    'فمتى عَلم العبدُ هذا من الرسول استسلم له، وسلَّم إليه، وانقادت كلُّ ذرّةٍ منه.',
  ];
  for (const t of liked) {
    assert.equal(extractSentences(`تمهيدٌ سابق. ${t}`).length, 1, `رُدّ ما قُبل: ${t.slice(0, 35)}`);
  }
  for (const t of rejected) {
    assert.equal(extractSentences(`تمهيدٌ سابق. ${t}`).length, 0, `مرّ ما رُدّ: ${t.slice(0, 35)}`);
  }
});

