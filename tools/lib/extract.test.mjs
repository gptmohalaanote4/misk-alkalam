test('«عبد» اسمٌ لا وصف، والكنية تُضمّ في سلسلة النسب', () => {
  // خطأٌ وقع: «عبد» في قائمة ما لا يصلح فاعلاً، فسقط «عبد الله بن الزبير».
  assert.equal(extractBiography(`حدثنا فلان بن فلان، قال: كان عبد الله بن الزبير إذا قام في الصلاة كأنه عود، وكان يقول ذلك من الخشوع.`).length, 1);
  assert.equal(extractBiography(`حدثنا فلان بن فلان، قال: كان عبد الرحمن بن أبي نعم يواصل خمسة عشر يوما لا يأكل ولا يشرب.`).length, 1);
});

test('القوس المعقوف المفرد من جهاز الطبعة يُحذف', () => {
  const out = extractBiography(`حدثنا فلان بن فلان، قال: كان حسان بن عطية يتنحى إذا صلى العصر فيذكر الله حتى تغيب الشمس].`);
  assert.equal(out.length, 1);
  assert.ok(!out[0].includes(']'), out[0]);
});

