/**
 * استخراج النصوص من صفحات «تراث» — دوالٌ خالصة بلا شبكة ولا ملفات.
 *
 * هذه البوّابات هي الضمان الوحيد بين «تراث» والمستخدم، لأن الحصد الآلي يُضيف
 * محتوىً بلا مراجعة بشرية. القاعدة: **ما دون اليقين يُسقَط**، ولا يُؤجَّل ولا
 * يُخمَّن. ولأنها كذلك فهي مُختبَرة في `extract.test.mjs` على نصٍّ حقيقي.
 */
import { fingerprint, plain } from './turath.mjs';

/** طول النص المقبول — أقصر منه ليس فائدة، وأطول منه لا يُقرأ في إشعار. */
export const MIN_CHARS = 60;
export const MAX_CHARS = 340;

/** ما يُسقِط النص فوراً. */
const REJECT = [
  /﴿|﴾|﴿/, // آية — لا نقتطع قرآناً
  /\(\^/, // إحالة حاشية
  /_{3,}/, // فاصل الحواشي
  /\[[^\]]*:/, // إحالة مثل [البقرة: ٢١٦]
  /[0-9٠-٩]/, // أرقام: صفحات أو حواشٍ أو تعداد مقطوع
  /\.{3}|…/, // كلام محذوف
];
export const hasRejected = (text) => REJECT.some((re) => re.test(text));

/** ما يدلّ على أن الباب في الفضائل. */
const MERIT_WORDS = ['فضل', 'فضائل', 'ثواب', 'كفارة', 'كفارات'];

/**
 * كتب الصحيحين التي موضوعها **الأعمال**. بوّابة لازمة فوق كلمة الفضل، لأن في
 * الصحيحين كتباً في الفضائل لا تخصّ عملاً — «كتاب فضائل الصحابة»،
 * و«كتاب المناقب»، و«كتاب الفضائل» في مسلم — فتمرّ لو اكتُفي بالكلمة.
 * قائمةٌ صريحة تُراجَع بالعين، لا قاعدة تُخمّن.
 */
const DEED_CHAPTERS = [
  'الإيمان', 'العلم', 'الطهارة', 'الوضوء', 'الغسل', 'التيمم',
  'الصلاة', 'المساجد', 'مواقيت', 'الأذان', 'الجمعة', 'الوتر', 'التهجد', 'التطوع',
  'الجنائز', 'الزكاة', 'الصدقة', 'الصوم', 'الصيام', 'التراويح', 'الاعتكاف',
  'فضائل القرآن', 'الحج', 'العمرة', 'الجهاد', 'الإمارة',
  'الأدب', 'البر', 'الرقاق', 'الدعوات', 'الذكر', 'التوبة', 'النفقات',
];

export const isDeedChapter = (chapter) =>
  Boolean(chapter) && DEED_CHAPTERS.some((name) => chapter.includes(name));
export const isMeritBab = (bab) => Boolean(bab) && MERIT_WORDS.some((word) => bab.includes(word));

// ─────────────── تنظيف نصّ الصفحة ───────────────
/** علامة تحيط بالعناوين بعد التنظيف، فيُعرَف موضع كل باب في الصفحة. */
const MARK = '\u0001';
const HEADING = new RegExp(`${MARK}([^${MARK}]*)${MARK}`, 'g');
/**
 * `<hadeeth-N>` يحيط بالكلام المنقول في نصّ «تراث». والمتن الواحد قد يتقطّع إلى
 * قطعٍ عدّة **بنفس الرقم N** إذا عبَر حدّ صفحةٍ مطبوعة، فتُجمَع القطع المتتابعة.
 */
const HADEETH_PIECE = /<hadeeth-(\d+)>([\s\S]*?)<hadeeth>/g;
/** علامة انتقال الصفحة المطبوعة داخل النص: ⦗٨٦⦘ */
const PAGE_BREAK = /⦗[^⦘]*⦘/g;
/** رقم الحديث يسبق إسنادَه بالأرقام العربية: «٢٣٣ - حدثنا…». */
const HADITH_NUMBER = /(^|\n)\s*([٠-٩]+)\s*-\s/g;
/**
 * الكلام منسوبٌ إلى النبي ﷺ نصّاً: ذِكرُه ثم فعل قولٍ ثم نقطتان، متّصلاً بالمتن.
 * بهذا يُستثنى ما كان من كلام الصحابي أو حكايةِ الراوي وإن كان في الوسم نفسه.
 * يُطبَّق على النص بعد `plain`، فلا يتعلّق الحكم برسم التشكيل.
 */
const PROPHET_SPEECH =
  /(رسول الله|النبي|رسول اللہ)\s*[^:؛.]{0,30}?(قال|يقول)\s*:\s*$/;
/** المتن المكتمل محوطٌ بعلامتَي التنصيص في المطبوع. */
const QUOTED = /^«[\s\S]*»\s*\.?$/;
/** حدّ المسافة بين رقم الحديث ومتنه — الإسناد أقصر من هذا بكثير. */
const ISNAD_WINDOW = 1200;

const ARABIC_DIGITS = { '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4', '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9' };
const toLatinDigits = (text) => text.replace(/[٠-٩]/g, (digit) => ARABIC_DIGITS[digit]);
const positiveInt = (value) => {
  const n = Number.parseInt(String(value ?? '').replace(/[^\d]/g, ''), 10);
  return Number.isInteger(n) && n > 0 ? n : null;
};

/**
 * تجريدٌ خاصٌّ لفحص نسبة الكلام: يُسقط التشكيل والوسوم والرموز، **ويُبقي
 * النقطتين** — لأنهما حدُّ بداية الكلام المنقول، و`plain` يُسقطهما.
 */
const DIACRITICS = /[ؐ-ًؚ-ٰٟۖ-ۭـ]/g;
const speechForm = (text) =>
  String(text)
    .replace(/<[^>]*>/g, ' ')
    .replace(DIACRITICS, '')
    .replace(/[^ء-ي\s:]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

/** يحذف الحواشي، ويفكّ وسوم أسماء الرجال، ويُعلِّم العناوين بمواضعها. */
export function cleanPage(raw) {
  return String(raw)
    .split(/\n_{3,}/)[0] // كل ما بعد فاصل الحواشي ليس من المتن
    .replace(/<a\s[^>]*>([\s\S]*?)<\/a>/g, '$1') // رابط اسم الراوي → اسمه
    .replace(/<span[^>]*>([\s\S]*?)<\/span>/g, `\n${MARK}$1${MARK}\n`);
}

/** يجرّد النص من الوسوم ويضبط مسافاته، مع إبقاء التشكيل والترقيم كما طُبع. */
export function tidy(text) {
  return String(text)
    .replace(/<[^>]*>/g, ' ')
    // علامة الحاشية «(^١)» من جهاز المحقّق لا من كلام المؤلف، فحذفها لا يمسّ النص.
    .replace(/\(\^[^)]*\)/g, ' ')
    .split(MARK)
    .join(' ')
    .replace(PAGE_BREAK, ' ')
    // كيانات HTML تصل من «تراث» كما هي، و«=» علامةُ ربطٍ عند المحقّق لا من النص.
    .replace(/&quot;/g, '')
    .replace(/&[a-z]+;|&#\d+;/gi, ' ')
    .replace(/\s*=\s*/g, ' ')
    .replace(/[«»]/g, '')
    .replace(/﵁|﵂|﵃|﵄|﵊|ﷺ/g, ' ')
    .replace(/\s+/g, ' ')
    // قوسٌ معقوفٌ مفردٌ من جهاز الطبعة (عناوينها بين معقوفين) لا من النص، فيُحذف
    // كما تُحذف علامة الحاشية. ولو بقي لظهر في الإشعار: «حتى تغيب الشمس].»
    .replace(/^\s*[\]\[]\s*|\s*[\]\[](?=\s*[.؟!]?\s*$)/g, '')
    .replace(/\s+([،؛:.!؟])/g, '$1')
    .trim();
}

/** نصٌّ مكتمل: يبدأ بحرفٍ عربي وينتهي بعلامة ختام. */
export const isComplete = (text) =>
  /^[ء-ي]/.test(text) && /[.؟!]$/.test(text);

/** يقبل النصّ طولاً ونظافةً واكتمالاً — البوّابة المشتركة بين الآليتين. */
export const isPublishable = (text) =>
  Boolean(text) &&
  isComplete(text) &&
  text.length >= MIN_CHARS &&
  text.length <= MAX_CHARS &&
  !hasRejected(text);

// ─────────────── بوّابة المرجع المطبوع ───────────────
/**
 * مرجعُ الصفحة المطبوع، أو `null` فلا تُحصد.
 *
 * **مجلّدٌ أو صفحةٌ غير مرقَّمة** = مقدّمةُ محقّقٍ أو فهرس، لا كلام المؤلف.
 *
 * والمجلّد يلزمه أن يكون **رقماً محضاً**: تجريدُ غير الأرقام يجعل «سيرة 1»
 * مجلّداً أولَ و«سيرة 2» ثانياً — وهما مجلّدا **السيرة النبوية** المُصدَّرة بها
 * «سير أعلام النبلاء — ط الرسالة»، لا مجلّدا الكتاب. فكان الخبر يُنسب إلى
 * «سير أعلام النبلاء ج٢ ص١٤» وهو في غيره، ومرجعٌ كاذبٌ أسوأُ من لا مرجع.
 * وفي الطبعة نفسها «راشدون» مجلّدٌ آخر — وهو يسقط لأنه بلا رقم أصلاً.
 */
export function printedRef(meta) {
  const page = positiveInt(meta?.page);
  if (!page) return null;
  const label = meta?.vol == null ? '' : String(meta.vol).trim();
  // كتابٌ لا يذكر مجلّداً أصلاً: المرجعُ صفحتُه وحدها.
  if (label === '') return { page, volume: null };
  if (!/^\d+$/.test(label)) return null;
  const volume = positiveInt(label);
  return volume ? { page, volume } : null;
}

// ─────────────── كشف التكرار ───────────────
/** أقلّ عدد كلمات مشتركة في المطلع يُعدّ بها النصّان واحداً. */
const MIN_SHARED_WORDS = 6;
/**
 * طولُ المطلع الذي يُقارَن به — وهو نفسه في `validate-content.mjs`.
 * فما يُنبّه عليه المُتحقِّق يمنعه الحاصد، ولا يتفاوت الحكمان.
 */
const OPENING_WORDS = 10;

/**
 * نصّان واحدٌ في المعنى — بأحد وجهين:
 *
 *   • أحدهما **مطلعُ** الآخر: الحديث يُروى في موضعين برقمين وتزيد إحدى الروايتين
 *     كلماتٍ في آخرها، فبصمة النص كلّه لا تكشفها.
 *   • أو يفترقان في **وسطهما**: الخبرُ الواحد عن الصالح يُطبَع في كتابَي سِيَرٍ
 *     بفرق حرفٍ أو كلمة — «اضطربت مفاصله حتى **تبين** الرعدة» و«حتى **تتبين**»،
 *     و«فيذكر **الله**» و«فيذكر **الله عز وجل**». والبادئةُ لا تكشف هذا، لأن
 *     واحدهما ليس مطلعَ الآخر؛ فيُقارَن المطلعُ بطوله المحدود.
 *
 * وكلاهما يصل المستخدم نصّين متشابهين — وهو ما لا يُقبل.
 */
export function sameText(a, b) {
  if (a === b) return true;
  const [short, long] = a.length <= b.length ? [a, b] : [b, a];
  const shortWords = short.split(' ');
  if (shortWords.length < MIN_SHARED_WORDS) return false;
  if (long.startsWith(`${short} `)) return true;
  // ودون `OPENING_WORDS` كلمةً يصير المطلعُ هو النصَّ القصيرَ كلَّه، فلا يُطابِق
  // إلا أن يكون بادئةَ الآخر — وقد فُحص ذلك قبله.
  if (shortWords.length < OPENING_WORDS) return false;
  const head = (words) => words.slice(0, OPENING_WORDS).join(' ');
  return head(shortWords) === head(long.split(' '));
}

/** يعيد النصّ المطابق من المجموعة، أو null. */
export function findDuplicate(text, existing) {
  const print = fingerprint(text);
  for (const other of existing) {
    if (sameText(print, other.print)) return other;
  }
  return null;
}

// ─────────────── استخراج المقولات ───────────────
/**
 * يستخرج فوائد الصفحة المفصولة بـ «•». يُسقِط ما قبل أول نقطة (فهو تتمّة
 * الصفحة السابقة)، وما لم ينتهِ بعلامة ختام (فهو يتمّ في الصفحة التالية).
 */
export function extractBulleted(pageText) {
  const parts = cleanPage(pageText).split('•');
  if (parts.length < 2) return [];
  return parts.slice(1).map(tidy).filter(isPublishable);
}

// ─────────────── استخراج الجمل من كتب النثر ───────────────
/**
 * الجملة المعتمِدة على ما قبلها: تبدأ بأداة وصلٍ أو إشارةٍ إلى سابق، فلا تُفهم
 * وحدها. والواو والفاء تُرفض بإطلاق وإن كانتا من بنية الكلمة («فضل»)، لأن
 * التمييز لا تضبطه قاعدة، والصفحات أكثر من أن نحتاج إلى المشكوك فيه.
 */
const LEADING_PARTICLE = /^(?:ثم|بل|لكن|لكنَّ|إذ|إذًا|أي|أو|حتى|لأن|كما|فإن|وإن|فلما|ولما|وأما|فأما)\s/;
/**
 * ما يُحيل إلى سابقٍ فلا تُفهم الجملة بدونه. والواو والفاء تُقبلان وحدهما —
 * فهما في النثر الكلاسيكي أداتا ربطٍ لا تبعية — إلا أن يتلوهما أحدُ هذه.
 */
const ANAPHORA = /^(?:هذا|هذه|هذان|ذلك|تلك|هؤلاء|أولئك|هو|هي|هم|هما|كذلك|لهذا|لذلك|هكذا|أما|فيه|فيها|منه|منها|به|بها|له|لها|عليه|عليها|إليه|إليها|عنه|عنها)(?:\s|$)/;

/**
 * ما يدلّ على أن الكلام منقولٌ عن غير المؤلف.
 * هذه أخطر بوّابة: لو مرّت جملةٌ ينقل فيها المؤلف قولَ غيره لنُسب إليه ما ليس
 * له. فيُرفض كل ما فيه فعلُ قولٍ أو روايةٍ أو رمزُ صلاةٍ أو ترضٍّ أو تنصيص.
 */
// «قوله» و«رواه» و«حديث» أُضيفت بعد أن مرّ: «وحديث: من دلَّ على خيرٍ فله مثلُ
// أجر فاعله، وهو حديثٌ حسنٌ رواه الترمذي» — حديثٌ من غير الصحيحين كاد يُنشر
// **مقولةً لابن القيم**، وقاعدةُ الأحاديث: الصحيحان حصراً.
const REPORTED_SPEECH = /قال|يقول|قالت|قيل|قوله|سمعت|سمع|روى|روي|رواه|يروي|أخرجه|حديث|حدثنا|حدثني|أخبرنا|أخبر|أنشد|ﷺ|﵁|﵂|صلى الله عليه|رضي الله عن|«|»|"/;

/**
 * رؤوس الأقسام في المطبوع («فصل»، «فائدة»، «تنبيه») تُطبع في سياق السطر، فتلتصق
 * بأوّل الجملة. وما التصق بها ليس مبتدأ كلامٍ مستقل.
 */
const SECTION_HEAD = /^(?:فصل|فائدة|تنبيه|مسألة|قاعدة|تتمة|خاتمة|مقدمة|الوجه|الفرق|الدرجة|المرتبة)(?:\s|:)/;

/**
 * مباحث اللغة والنحو في كتب المؤلف: صحيحةٌ، لكنها ليست مما يُرسَل تذكيراً
 * يومياً. تُبعَد بمفرداتها المميّزة.
 */
const TECHNICAL = /وزن|فعول|الاشتقاق|مادّة|مادة|النحو|الصرف|إعراب|اللفظة|صيغة|الضمير|تكسير|المعدول|المصدر/;

/**
 * ما يُحيل إلى تعدادٍ سابق: «الثانية…»، «أحدها…»، «ومنها…».
 * والقائمةُ تمتدّ إلى آخر العقد وإلى المثنّى، بعد أن مرّ «العاشر: انقسامُ خلقه…»
 * و«أحدهما: دينه الأمريُّ…» — وهما بندا قائمةٍ لا يُفهمان وحدهما.
 */
const ENUMERATOR =
  /^(?:الأول|الأولى|الثاني|الثانية|الثالث|الثالثة|الرابع|الرابعة|الخامس|الخامسة|السادس|السادسة|السابع|السابعة|الثامن|الثامنة|التاسع|التاسعة|العاشر|العاشرة|الحادي|أحدها|إحداها|أحدهما|إحداهما|ومنها|منها|الوجه|القسم|النوع|الدرجة|المرتبة|الصنف|الطبقة|الباب|الفصل)(?:\s|$|:)/;

/**
 * الفحص على النصّ المجرَّد من التشكيل: «وأمَّا» و«الثانية» لا تُطابقان قوائمَ
 * غير مشكولة، فتمرّ الجملة المعتمِدة على سابقها لو فُحصت مشكولة.
 */
/** أعدادُ الترتيب — تُطابَق مجرّدةً من التشكيل. */
const ORDINAL =
  /(?:^|\s)(?:الأول|الأولى|الثاني|الثانية|الثالث|الثالثة|الرابع|الرابعة|الخامس|الخامسة|السادس|السادسة|السابع|السابعة|الثامن|الثامنة|التاسع|التاسعة|العاشر|العاشرة)(?:\s|$)/;

/**
 * بندُ قائمةٍ يُصدَّر بنقطتين: «ومن الصبر الثاني: إنشاءُ الله…»، و«الفائدة
 * الخامسة: أنَّه يُورث قوّةَ القلب…». الترتيبُ فيه ليس في أول الكلام — فلا
 * يكشفه `ENUMERATOR` — بل في صدرٍ قصيرٍ قبل النقطتين. وما بعده تتمّةُ تعدادٍ
 * لا يُفهم وحده.
 */
const isListItem = (text) => {
  const head = text.split(':')[0];
  if (head === text) return false;
  const words = head.trim().split(/\s+/);
  if (words.length > 5) return false;
  // والترتيبُ في **أول** الصدر لا في آخره: «الفائدة الخامسة:» بندُ قائمة، أمّا
  // «التوكل نصف الدين، والنصف الثاني:» فحكمةٌ تامّة جاء العددُ في عَجُزها.
  return ORDINAL.test(plain(words.slice(0, 2).join(' ')));
};

/**
 * **الحكمةُ تبتدئ باسمٍ أو فعل، لا بواوٍ ولا فاء.**
 *
 * كانت الواو والفاء تُقبلان بتعليل: «هما في النثر الكلاسيكي أداتا ربطٍ لا
 * تبعية». والتعليلُ صحيحٌ نحواً، خاطئٌ لغرضنا: الإشعارُ يصل وحده، والواوُ
 * تُخبر أن قبله كلاماً — فلا تُفهم الجملة إلا بما قُطعت عنه.
 *
 * وقِيس هذا على ما قبله صاحب المشروع وما ردّه: ستُّ مقولاتٍ أعجبته كلُّها
 * تبتدئ باسم («العلم نورٌ يقذفه الله…»، «التوكل نصف الدين»، «الشكر: ظهورُ
 * أثر نعمة الله…»)، وثمانٍ ردَّها كلُّها تبتدئ بواوٍ أو فاء. فصلٌ تامّ
 * أربعةَ عشرَ من أربعةَ عشر.
 */
const startsConnected = (bare) => /^[وف]/.test(bare);

/**
 * `allowConnective` تُرخِّص الواو والفاء في المطلع — **للمجاميع وحدها**.
 * ففي النثر المتّصل تدلّ الواوُ أن الجملة قُطعت عمّا قبلها، وفي المجموع تدلّ
 * على سردٍ جديد: الفقرةُ وحدةٌ مطبوعةٌ قائمةٌ بنفسها ومعها نسبتُها («وقال
 * الحسن البصري: يا ابن آدم، إنما أنت أيام…»). وتطبيقُ القاعدة عليها أنزل
 * «قيمة الزمن» من ٢١٦ إلى ٥١.
 */
const isSelfContained = (text, { allowConnective = false } = {}) => {
  if (isListItem(text)) return false;
  const bare = plain(text);
  if (!allowConnective && startsConnected(bare)) return false;
  // الواوُ والفاء تُجرَّدان قبل فحص التعداد ورأس القسم كما تُجرَّدان قبل
  // الإشارة: «ومن الصبر الثاني:» و«وحالة أخرى» بندا قائمةٍ وإن سبقتهما واو.
  const stem = bare.replace(/^[وف]/, '');
  return (
    !LEADING_PARTICLE.test(bare) &&
    !SECTION_HEAD.test(stem) &&
    !ENUMERATOR.test(stem) &&
    !TECHNICAL.test(bare) &&
    !ANAPHORA.test(stem)
  );
};
const isReported = (text) => REPORTED_SPEECH.test(plain(text)) || /[«»"]|ﷺ|﵁|﵂/.test(text);

/**
 * شرحُ المفردات والصرف — لا موعظة.
 *
 * كتبُ ابن القيم تتخلّلها فصولٌ في اللغة: «والكَمَد: الحزن المكتوم، تقول منه:
 * كَمِدَ الرجل»، و«سَهِدَ الرجل ــ بالكسر ــ يَسْهَد سَهَدًا». وهي جملٌ مطبوعةٌ
 * تامّةٌ مستقلّة، فتمرّ كلَّ بوّاباتنا — ولا تصلح أن تصل المستخدم في إشعارٍ
 * يومي. **قرارُ صاحب المشروع: غيرُ مناسبةٍ أبداً.**
 *
 * والعلامات ضبطُ الحركة وصيغُ الصرف، وهي لا تَرِد في الموعظة.
 *
 * ولا `\b` هنا: حدُّ الكلمة لا يعمل مع العربية في JavaScript — وهو خطأٌ مُثبَتٌ
 * في `CLAUDE.md` وقد وقع فيه هذا الموضع مرةً فمرّت الثلاثةُ كلُّها. فالمطابقة
 * على النصّ بعد `plain` (مجرَّداً من التشكيل)، وبمسافةٍ أو أوّلِ نصٍّ قبل الكلمة.
 */
const LEXICAL =
  /(?:^|\s)(?:بالكسر|بالفتح|بالضم|بكسر|بفتح|بضم|وكسرها|وفتحها|وضمها|بالتشديد|بالتخفيف|مكسورة|مفتوحة|مضمومة|تقول منه|يقال منه|على وزن|وزنه|على افتعل|لغتان|لغة فيه|جمعه|جمعها|مثناه|تصغيره|مصدره)(?:\s|$)/;

/**
 * مسائلُ الإعراب — من صنعة النحويّ لا من الموعظة.
 * «وعلى هذا فيكونُ العائدُ منصوبًا محذوفًا، وحذفُه في مثل ذلك قياسٌ مطَّرد».
 * وتُنتقى الألفاظُ التي لا تَرِد إلا في الإعراب، فلا تُردّ موعظةٌ بلفظٍ مشترك
 * («الخبر» و«الصيغة» مشتركان فلا يدخلان).
 */
const GRAMMAR =
  /(?:^|\s)(?:منصوب|منصوبا|مرفوع|مرفوعا|مجرور|مجرورا|مجزوم|إعرابه|اعرابه|العائد|قياس مطرد|اسم الفاعل|اسم المفعول|الضمير المستتر|حرف الجر|معطوف)(?:\s|$)/;

/**
 * السؤال لا يُرسَل وحده: «كيف يجد العبد أبوابَ الخير مسدودةً؟» جوابُه بعده في
 * الكتاب، فالجملةُ تامّةٌ طباعةً ناقصةٌ معنىً. (ومثلُه في أخبار الصالحين يردّه
 * `isNarrative`.)
 */
const isQuestion = (text) => /[؟?]\s*$/.test(text.trim());

/**
 * يستخرج الجمل المطبوعة التامّة من صفحة نثر.
 *
 * الحدّ هو **الجملة كما طُبعت**: ما بين علامتَي ختام. وتُشترط فيها شروطٌ فوق
 * شروط النشر العامة:
 *   • أن تكون مُحاطة بعلامتَي ختامٍ داخل الصفحة — فأوّلُ الصفحة تتمّةُ ما قبلها.
 *   • أن تستقلّ بنفسها فلا تبدأ بأداة وصلٍ ولا إشارةٍ إلى سابق.
 *   • ألّا يكون فيها نقلٌ عن غير المؤلف، **ولا في الجملة التي قبلها** — فالنسبة
 *     قد تتقدّم على المنقول.
 */
export function extractSentences(pageText) {
  const clean = cleanPage(pageText).replace(HEADING, ' . ').replace(PAGE_BREAK, ' ');
  const parts = clean.split(/(?<=[.؟!])\s+/);
  const out = [];

  parts.forEach((raw, index) => {
    // أوّل جزءٍ تتمّةُ الصفحة السابقة، وما لم يُختم لم يتمّ في هذه الصفحة.
    if (index === 0 || !/[.؟!]\s*$/.test(raw)) return;
    const text = tidy(raw);
    if (!isPublishable(text) || !isSelfContained(text) || isReported(text)) return;
    const bare = plain(text);
    if (LEXICAL.test(bare) || GRAMMAR.test(bare) || isQuestion(text)) return;
    if (isReported(tidy(parts[index - 1] ?? ''))) return;
    out.push(text);
  });

  return out;
}

// ─────────────── استخراج أخبار الصالحين ───────────────
/** حدّ الخبر: خمسون كلمةً فأقل بطلب صاحب المشروع، وستٌّ فأكثر ليكون خبراً. */
const BIOGRAPHY_MAX_WORDS = 50;
const BIOGRAPHY_MIN_WORDS = 6;

/**
 * مطلعُ الخبر عن الصالح: «كان فلانٌ…»، وما جرى مجراه.
 * الشرط في المطلع لا في المعنى، فينضبط بلا حكمٍ على المضمون.
 */
const BIOGRAPHY_OPENER = /^(?:كان|كانت|وكان|وكانت|فكان|فكانت)\s/;

/** أداةٌ أو ظرفٌ لا يصلح فاعلاً: تُطابَق كلمةً كاملة. */
const PARTICLE =
  /^(?:إذا|إذ|إن|أن|قد|لا|ما|في|على|من|عند|بين|ذلك|هذا|هذه|له|لها|عنده|معه|يوما|أحد|ممن|مما|كذلك|ثم)$/;

/**
 * الفعل المضارع يبدأ بحرف مضارعة: «كان يصلي…» فاعلُها ضميرٌ مستتر يعود إلى
 * ترجمةٍ قبلها. (الشرط على **بداية الكلمة** لا على حرفٍ مفرد — وهذا موضع خطأٍ
 * سابق جعل «يصلي» تمرّ.)
 */
const isVerbLike = (word) => /^[يتن]/.test(word) && word.length > 2;

/** ما أُضيف إلى ضمير المتكلّم أو جماعته: «أمي»، «شيخنا» — لا يُعرف صاحبه. */
const POSSESSIVE =
  /^(?:أمي|أبي|جدي|جدتي|أخي|أختي|ابني|ابنتي|عمي|خالي|صاحبي|شيخي|شيخنا|أمه|أبوه|أخوه|صاحبه|شيخه|أصحابنا|إخواننا)$/;

/**
 * أسماء الأجناس والجموع: «كان الجنُّ…»، «كان المسلمونَ…» أخبارٌ عامّة لا
 * ترجمةُ صالحٍ يُقتدى به. و«ال» وحدها لا تدلّ على العَلَم.
 */
/**
 * لا يُقتدى بخبرٍ فاعلُه ليس رجلاً معيَّناً من الصالحين:
 *   • الله ﷿ — «كان الله تعالى يتعاهد الناس بنبيٍّ بعد نبي» خبرٌ عن الله لا ترجمة.
 *   • نبيٌّ — فما جاء عن الأنبياء مصدره الصحيحان، لا كتب السِّيَر.
 *   • جنسٌ عامّ («كان المؤمن…») فهو قولٌ لا خبر، وأهلُ بيتٍ («كان آل ابن سيرين…»).
 *   • معنىً لا شخص: «كانت فتنةُ ابن الزبير تسع سنين».
 */
const NOT_A_PERSON = new Set(
  ('الله لله الرب ربنا الحق المولى المؤمن العبد المسلم الرجل المرء المرأة آل أمر شأن فتنة ' +
    'عيسى موسى إبراهيم نوح يوسف يونس يحيى هارون داود سليمان آدم إدريس إسماعيل إسحاق يعقوب أيوب')
    .split(' '),
);

const COLLECTIVE =
  /^(?:ال)?(?:جن|ناس|قوم|عرب|صحابة|ملائكة|نساء|رجال|مسلم|كفار|مشرك|أنصار|مهاجر|خلق|أمة|سلف|علماء|فقهاء|قراء|عباد|زهاد|أهل|بنو|بني|شيطان|دنيا|أرض|سماء|يهود|نصارى|ملوك|أمراء|خلفاء)/;
const PLURAL_END = /(?:ون|ين|ات|اء)$/;

/** الكنية والنسبة تُطابَق **كلماتٍ كاملة**: «أمي» ليست «أم»، و«كانت» ليست «كان». */
const KUNYA = /^(?:أبو|أبا|أبي|أم|ابن|ابنة|بنت|عبد|الإمام|الشيخ|القاضي|أمير)$/;
const NISBA = /^(?:بن|بنت|ابن)$/;

/**
 * الاسم على صيغة الأعلام: كنيةٌ مفردة («أبو الدرداء»)، أو مُعرَّفٌ بـ«ال» ليس
 * جنساً ولا جمعاً («الحسن»)، أو تلته نسبة («سفيان بن عيينة»).
 */
/**
 * طول اسم الصاحب بالكلمات، أو صفرٌ إن لم يكن اسماً.
 * صيغتان لا ثالثة، لأن ما سواهما يُدخل الأفعال والأوصاف: «كان حالف الأسودَ…»
 * فعلٌ ماضٍ، و«كان صائماً الدهرَ» وصفٌ — وكلاهما خبرٌ بلا صاحبٍ مسمّى.
 *   ١) كنيةٌ ثم اسم: «أبو الدرداء».
 *   ٢) علمٌ مُعرَّف بـ«ال»، أو علمٌ تلته نسبةٌ بـ«بن».
 * ثم تُضمّ النسبة التالية إن كانت مُعرَّفة: «الحسن البصري».
 */
const nameLength = (words) => {
  const [first = '', second = ''] = words;
  if (!first || COLLECTIVE.test(first) || PLURAL_END.test(first)) return 0;

  let n = 0;
  if (KUNYA.test(first) && second) n = 2;
  else if (/^ال/.test(first) && first.length > 3) n = 1;
  else if (NISBA.test(second) && words[2]) n = 3;
  if (n === 0) return 0;

  // «عبد الرحمن بن أبي نعم»: بعد «بن» كنيةٌ لا علمٌ مفرد، فتُضمّ بكلمتيها.
  while (NISBA.test(words[n]) && words[n + 1]) {
    n += KUNYA.test(words[n + 1]) && words[n + 2] ? 3 : 2;
  }
  if (/^ال/.test(words[n] ?? '') && (words[n] ?? '').length > 3) n += 1;
  return n;
};

/**
 * «كان فلانٌ إذا جنّ عليه الليل…»: الشرط بعد «كان» صيغةُ عادةٍ في نفسه، فيُقبل
 * ولو كان فعلُه ماضياً في اللفظ.
 */
const HABIT_OPENER = /^(?:إذا|كلما|إن)$/;
/** «لا يدع»: أداةٌ يليها مضارع، فالخبر عملٌ لا وصف. */
const DEED_PARTICLE = /^(?:لا|ما|ثم|حتى|قد)$/;

const NAME_SHAPED = (after) => nameLength(after.split(' ').filter(Boolean)) > 0;

/**
 * صاحب الخبر مُسمّىً باسمٍ ظاهر. البوّابة واحدةٌ تجمع الشروط كلَّها، لأن تفريقها
 * هو ما أفلت منه «كان يصلي الليل» — مرّ على صيغة الاسم ولم يُختبر فعلاً.
 */
const namedSubject = (after) => {
  const words = after.split(' ').filter(Boolean);
  const first = words[0] ?? '';
  if (!first) return false;
  if (PARTICLE.test(first) || POSSESSIVE.test(first) || isVerbLike(first)) return false;
  if (NOT_A_PERSON.has(first)) return false;
  const n = nameLength(words);
  if (n === 0) return false;
  // و«يعني» شرحُ ناقلٍ للاسم لا فعلَ صاحبه: «كان معاوية بن خديج - يعني أبا زهير -».
  if ((words[n] ?? '') === 'يعني') return false;
  // وبعد الاسم **فعلٌ مضارع** يدلّ على العادة — وهي صيغة الطلب: «كان فلانٌ يفعل كذا».
  // فما كان وصفاً لذاته («كان معاذٌ شابًّا جميلًا») يُسقَط، إذ المطلوب العملُ.
  const next = words[n] ?? '';
  return (
    isVerbLike(next) ||
    HABIT_OPENER.test(next) ||
    (DEED_PARTICLE.test(next) && isVerbLike(words[n + 1] ?? ''))
  );
};

/**
 * الحكاية ذات الحوار ليست وصفَ عملٍ يُقتدى به، بل قصّةٌ لا تُفهم مقتطعة.
 * و«يقول» الدالّة على العادة تبقى: «كان سفيان يقول لأصحابه…».
 */
const DIALOGUE_WORDS = new Set(
  'قال قالت فقال فقالت وقال فقلت قلت وقلت فأجاب أجاب قيل فقيل سأله فسأله سألته'.split(' '),
);

/**
 * حدُّ الكلمة في JavaScript لا يعمل مع العربية، فالمطابقة على **قائمة كلماتٍ**
 * مجرّدةٍ من التشكيل لا على نمطٍ بحدود كلمات. (وقد أفلتت بسببه حكايةٌ تنتهي
 * بـ«ما اسمك؟».)
 */
const isNarrative = (bare, text) =>
  text.includes(': ') || bare.split(' ').some((w) => DIALOGUE_WORDS.has(w));

/**
 * ما لا يصلح خبراً عن صالح:
 *   • ما نُسب إلى النبي ﷺ — فالأحاديث من الصحيحين وحدهما، لا من كتب السير.
 *   • ما كان إسناداً أو جرحاً وتعديلاً أو تأريخَ وفاةٍ لا عملَ صالحٍ يُقتدى به.
 */
const BIOGRAPHY_REJECT =
  /ﷺ|﵇|صلى الله عليه|عليه السلام|رسول الله|النبي|حدثنا|حدثني|أخبرنا|أنبأنا|سمعت منه|ثقة|ضعيف|متروك|مات سنة|توفي سنة|ولد سنة|روى عنه|روى له/;

/**
 * إحالةُ المحدّث لا متنَ خبر: «كان مطرف بن عبد الله يدعو فذكر مثله» — الخبر نفسه
 * في موضعٍ آخر، وهذه إشارةٌ إليه. وحاشيةُ المحقّق في اللغة والرسم ليست من الخبر.
 */
const REFERRAL = /فذكر مثله|نحوه|بمثله|بإسناده|مثل حديث|وهي كلمة|بالفتح|بالكسر|بالضم|كذا في الأصل|المعجمة|المهملة/;

/**
 * خطابٌ للراوي لا وصفُ عادة: «كان بشر بن منصور **يقول لي** اجعل العلم فضلا» —
 * وصيّةٌ لرجلٍ بعينه، لا عملٌ كان يفعله.
 */
const ADDRESSED = /(?:يقول|ويقول|فيقول|قال|يكتب)\s+(?:لي|لنا)(?:\s|$)/;

/**
 * إحالةٌ على خبرٍ سابق: «وكان سعيد بن المسيب **يقول ذلك**» — لا يُفهم وحده،
 * فمرجعُ «ذلك» في صفحةٍ قبله.
 */
const ENDS_REFERRAL = /(?:ذلك|مثله|نحوه|كذلك)\s*[.؟!]?\s*$/;

/**
 * ضميرٌ معلَّق في خبرٍ قصير: «كان الإمام أحمد بن حنبل يحمد سيرته.» — سيرةَ مَن؟
 * مرجعُ الهاء خارج الخبر، فلا يُفهم وحده. والخبر الطويل يُبيّن مرجعه بنفسه.
 */
const danglingPronoun = (words) => {
  const last = words[words.length - 1] ?? '';
  if (words.length > 8) return false;
  return (/ها$/.test(last) || /ه$/.test(last)) && !isVerbLike(last);
};

/** «يصنع كما يصنع هؤلاء الأئمة اليوم»: إشارةٌ إلى حاضر الراوي لا تُفهم وحدها. */
const DEICTIC = /هؤلاء/;

/**
 * ما جعل الخبرَ عن الراوي لا عن المترجَم له: ضميرُ المتكلّم أو جماعته متّصلاً
 * بحرفٍ («ينزل علينا بمكة»)، أو فعلٌ للمتكلّم («فكنت إذا نظرت إليه»). فالخبر
 * حينها حكايةُ لقاءٍ لا وصفَ عملٍ يُقتدى به.
 * و«إني» و«أنا» لا تُردّان، فهما من كلام الصالح نفسه: «ويقول: إني لأستحي…».
 */
const NARRATOR_SELF = new Set(
  ('علينا عندنا إلينا معنا فينا لنا منا بنا كنت فكنت وكنت رأيت فرأيت سمعت فسمعت دخلت أتيت ' +
    'صحبت سألت جاءني أتاني حدثني أخبرني لقيت شهدت خرجت مررت رأيته سمعته')
    .split(' '),
);

/**
 * ضميرُ المتكلّم لاحقاً بالفعل: «يعلمني القرآن»، «يجيئني فأقريه» — الخبر عن
 * الراوي. وتُستثنى الكلمات القصيرة لئلّا تُردّ كلمةٌ تنتهي بـ«ني» في أصلها.
 */
/**
 * ولا يُكتفى بلحاق «ني»: فالنسبة تنتهي بها («الخولاني») والاسم كذلك («ميزاني»).
 * فيُشترط أن تكون الكلمةُ فعلاً — أي تبدأ بحرف مضارعةٍ أو بواوٍ أو فاءٍ قبله.
 */
const firstPersonSuffix = (w) =>
  w.length >= 5 && w.endsWith('ني') && /^[وف]?[يتنأ]/.test(w);

/** مطلعُ كلام الصالح: ما بعده ضمائرُه هو، لا ضمائرُ الراوي. */
const SPEECH = new Set('يقول ويقول فيقول تقول وتقول يدعو ويدعو فيدعو يناديه'.split(' '));

const aboutNarrator = (bare) => {
  const words = bare.split(' ');
  const speech = words.findIndex((w) => SPEECH.has(w));
  const before = speech === -1 ? words : words.slice(0, speech);
  return before.some((w) => NARRATOR_SELF.has(w) || firstPersonSuffix(w));
};

/**
 * أبوابٌ لا يُحصد منها خبرُ صالح: سيرةُ النبي ﷺ (فحديثه من الصحيحين وحدهما)،
 * ومقدّمةُ الكتاب وفهارسه وترجمةُ مؤلّفه — سيرةٌ وتاريخٌ لا عملَ يُقتدى به.
 */
const SECTION_REJECT =
  /سيرة رسول الله|سيرة النبي|سيرة المصطفى|المقدمة|مقدمة|الفهرس|فهرس|خطبة الكتاب|ترجمة المؤلف|ترجمة المصنف|تمهيد/;

/**
 * الصفحة في بابٍ يصلح للحصد.
 * و«تراث» لا يذكر العنوان إلا في صفحة ابتدائه، فالعناوين تُحمل بين الصفحات —
 * ومن لم يُعرف بابُه بعدُ فهو في أوّل الكتاب قبل أول ترجمة، فلا يُحصد منه.
 */
export function biographySectionOk(headings) {
  if (!Array.isArray(headings) || headings.length === 0) return false;
  return !headings.some((h) => SECTION_REJECT.test(plain(String(h))));
}

const CONDITION = /^(?:إذا|فإذا|وإذا|كلما|فكلما|لما|فلما)$/;

/**
 * شكُّ الراوي في اللفظ: «كان عمرو بن عتبة يسوق أو يزود ركاب أصحابه». والخبر
 * نفسه يأتي في الصفحة بلفظٍ مجزوم، فالمشكوك فيه لا يُنشر وفيه غُنية.
 */
const narratorDoubt = (words) =>
  words.some((w, i) => w === 'أو' && isVerbLike(words[i - 1] ?? '') && isVerbLike(words[i + 1] ?? ''));
const PREPOSITION = new Set('إلى على في فى من عن مع عند بين نحو لدى'.split(' '));

/**
 * شرطٌ بلا جواب: «كان مالك بن دينار إذا أقام في محرابه.» — الجملة مطبوعةٌ تامّة
 * الحدّ، لكنها لا تُفهم وحدها، فجوابُ الشرط في سطرٍ تالٍ أو حوارٍ بعده. وعلامتُه
 * أن ما بعد آخر أداة شرطٍ كلمتان، أو ثلاثٌ آخرُها جارٌّ ومجرور.
 */
const danglingCondition = (words, nameEnd) => {
  let last = -1;
  words.forEach((w, i) => {
    if (CONDITION.test(w)) last = i;
  });
  if (last === -1) return false;
  const rest = words.slice(last + 1);
  // كلمتان فأقلّ بعد الشرط: لا جوابَ له أصلاً. «لا يغضب، فإذا أغضبه الرجل.»
  if (rest.length <= 2) return true;
  // وثلاثٌ آخرُها جارٌّ ومجرور تكفي **إن كان الشرط ملاصقاً للاسم**، فلا جملةَ
  // قبله تُفهم وحدها: «إذا أقام في محرابه». أمّا «لما يرى من فضله» فتعليلٌ بعد
  // خبرٍ تامّ، لا شرطٌ مقطوع.
  return rest.length === 3 && PREPOSITION.has(rest[1]) && last === nameEnd;
};

/**
 * يستخرج أخبار الصالحين من صفحة كتاب سِيَر: جملةٌ مطبوعة تامّة تبدأ بـ«كان»،
 * في حدود خمسين كلمة. والشرط شكليٌّ محض — لا حكم على المعنى — فما خرج عن
 * النمط يُترك، وما دخله فهو خبرٌ عن عملٍ بصيغته المطبوعة.
 */
export function extractBiography(pageText) {
  const clean = cleanPage(pageText).replace(HEADING, ' . ').replace(PAGE_BREAK, ' ');

  // في كتب السِّيَر يأتي الخبر داخل إسناد: «حدثنا فلانٌ… قال: كان الحسنُ…».
  // فالنقطتان بعد فعل القول حدٌّ مطبوع: ما قبلهما إسنادٌ، وما بعدهما الخبر.
  // (نفس مبدأ وسم المتن في الحديث: الحدّ من المطبوع لا من التقدير.)
  const reported = [...clean.matchAll(/قَالَ\s*:|قال\s*:|قَالَتْ\s*:|قالت\s*:/g)].map(
    (m) => clean.slice(m.index + m[0].length),
  );
  const parts = [...clean.split(/(?<=[.؟!])\s+/), ...reported.flatMap((r) => r.split(/(?<=[.؟!])\s+/).slice(0, 1))];
  const out = [];
  const seen = new Set();

  parts.forEach((raw, index) => {
    // ما جاء من الإسناد لا يُشترط فيه أن يسبقه ختامٌ، فحدُّه «قال:».
    const fromIsnad = index >= clean.split(/(?<=[.؟!])\s+/).length;
    if (!fromIsnad && (index === 0 || !/[.؟!]\s*$/.test(raw))) return;
    if (fromIsnad && !/[.؟!]\s*$/.test(raw)) return;
    const text = tidy(raw);
    if (seen.has(text)) return;
    seen.add(text);
    const bare = plain(text);
    if (!BIOGRAPHY_OPENER.test(bare)) return;
    // صاحب الخبر يجب أن يُسمّى فيه باسمٍ ظاهر، وإلا عُرض عملٌ بلا صاحب.
    const after = bare.replace(BIOGRAPHY_OPENER, '');
    if (!namedSubject(after)) return;
    if (isNarrative(bare, text)) return;
    // ما انتهى باستفهام حكايةٌ لم تتمّ، لا خبرُ عملٍ يُقتدى به.
    if (/؟\s*$/.test(text)) return;
    const words = bare.split(' ').filter(Boolean).length;
    if (words < BIOGRAPHY_MIN_WORDS || words > BIOGRAPHY_MAX_WORDS) return;
    if (hasRejected(text) || BIOGRAPHY_REJECT.test(bare)) return;
    if (aboutNarrator(bare)) return;
    if (REFERRAL.test(bare) || DEICTIC.test(bare)) return;
    const afterWords = after.split(' ').filter(Boolean);
    if (danglingCondition(afterWords, nameLength(afterWords))) return;
    if (narratorDoubt(afterWords)) return;
    if (ADDRESSED.test(bare) || ENDS_REFERRAL.test(bare)) return;
    if (danglingPronoun(afterWords)) return;
    if (!/[.؟!]$/.test(text)) return;
    out.push(text);
  });

  return out;
}

