/**
 * يصنّف عنواناً في الصفحة: كتابٌ، أو بابٌ، أو غيرهما.
 * التصنيف على النص المجرّد من التشكيل، لأن «تراث» يكتب العناوين مشكولة، وبعض
 * الطبعات تُرقّم عناوينها: «٤٥ - كتاب البر والصلة» — والرقم ليس من الاسم.
 */
export function classifyHeading(title) {
  const bare = plain(String(title).replace(/^\s*[٠-٩\d]+\s*-\s*/, ''));
  if (bare.startsWith('كتاب')) return { level: 'chapter', title: bare };
  if (bare.startsWith('باب')) return { level: 'bab', title: bare };
  return { level: 'other', title: bare };
}

/**
 * يجمع قطع المتن الواحد: القطع المتتابعة بنفس رقم الوسم متنٌ واحد تقطّع عند
 * حدّ صفحةٍ مطبوعة. يعيد كل متنٍ بموضع أوّل قطعةٍ منه ونصّه موصولاً.
 */
export function groupMatns(clean) {
  const groups = [];
  for (const match of clean.matchAll(HADEETH_PIECE)) {
    const [, id, body] = match;
    const last = groups[groups.length - 1];
    if (last && last.id === id) {
      last.body += ` ${body}`;
      continue;
    }
    groups.push({ id, index: match.index, body });
  }
  return groups;
}

/**
 * الصحابيات الراويات في الصحيحين — قائمة صريحة تُراجَع بالعين، لأن التأنيث لا
 * يُعرف من رسم الاسم بقاعدة: «عائشة رضي الله عنها» لا «عنه». وما سوى الكنية
 * بـ«أمّ» لا يُستدلّ عليه إلا بالمعرفة.
 */
const WOMEN = [
  'عائشة', 'فاطمة', 'زينب', 'حفصة', 'أسماء', 'ميمونة', 'سودة', 'جويرية',
  'صفية', 'رملة', 'سبيعة', 'خولة', 'الربيع', 'أنيسة',
];
const isFeminine = (name) =>
  /^أمّ?\s/.test(name) || WOMEN.some((w) => name === w || name.startsWith(`${w} `));

/** صحابةٌ يُذكرون باسمٍ مفرد، فلا تدلّ على أسمائهم بنيةُ «ابن/أبي/أم». */
const SINGLE_NAMES = [
  ...WOMEN, 'أنس', 'جابر', 'معاذ', 'بلال', 'حذيفة', 'سلمان', 'عمار',
  'ثوبان', 'سهل', 'أسامة', 'عدي', 'عمران', 'بريدة', 'واثلة',
];

/**
 * اختبارٌ بنيوي للاسم: كنيةٌ، أو نسبةٌ بـ«بن»، أو اسمٌ مفردٌ معروف.
 * بدونه يمرّ ما ليس باسمٍ أصلاً — ظهر فعلاً «يدعه» راوياً، لأن اسم الصحابي كان
 * يفصله عن موضع النسبة سردٌ طويل. والفراغ خيرٌ من نسبةٍ كاذبة.
 */
function looksLikeName(name) {
  const words = name.split(' ').filter(Boolean);
  if (words.length === 0) return false;
  if (/^(?:أبي|أبو|أبا|أم|أمّ|ابن|ابنة)$/.test(words[0])) return words.length >= 2;
  if (words.includes('بن') || words.includes('بنت')) return true;
  return words.length === 1 && SINGLE_NAMES.includes(words[0]);
}

/**
 * الصحابي الراوي: آخر اسمٍ ذُكر قبل نسبة الكلام إلى النبي ﷺ.
 * يعيد null عند أي لبس — الحقل يقبل الفراغ، والتخمين لا يُقبل.
 */
export function narratorOf(isnad) {
  // العمل على النص المجرّد من التشكيل: رسمُ الحروف سليم، والمطابقة لا تتعلّق بحركة.
  const bare = plain(isnad);
  const tail = bare.slice(-320);
  const anchor = tail.search(
    /(سمعت رسول الله|سمعت النبي|عن رسول الله|عن النبي|قال رسول الله|قال النبي|أن رسول الله|أن النبي|يقول رسول الله)/,
  );
  if (anchor <= 0) return null;

  // أدوات الإسناد تُقطّع السلسلة، فيبقى الاسم وحده. وما لم يُقطع منها يبقى في
  // أول الاسم فيظهر في الواجهة («عن سمع أبا هريرة») — فتُقتطع من أوله أيضاً.
  const CONNECTORS = '،|قالت|قال|عن|حدثنا|حدثني|أخبرنا|أخبرني|أنبأنا|سمعت|سمع|يحدث|يقول|أنه|أن';
  const parts = tail.slice(0, anchor).split(new RegExp(`\\s*(?:${CONNECTORS})\\s+`));
  // أسماء الصحابة فيها المفرد: «عائشة»، «أنس»، «جابر». فاشتراط كلمتين فأكثر
  // يتخطّاها إلى من قبلها في الإسناد — وهو تابعيّ، فتُنسب الرواية إلى غير صاحبها.
  const NOT_A_NAME = /^(?:رضي|الله|النبي|رسول|وسلم|عليه|عنه|عنها|عنهما)$/;
  // كلماتٌ لا تكون من الاسم، فيُقطع عندها: «عمر بن الخطاب على المنبر» اسمُه
  // «عمر بن الخطاب»، و«أم حبيبة تقول» اسمها «أم حبيبة».
  const STOP = /^(?:على|في|عند|بين|حين|يوم|وهو|وهي|وهم|ثم|تقول|يقول|قال|قالت|سأل|يسأل|سمع|أنه|أنها|يحدث|يخطب|كان|كانت)$/;

  const cleanName = (part) => {
    let words = part.trim().split(/\s+/).filter(Boolean);
    while (words.length > 0 && STOP.test(words[0])) words.shift();
    const cut = words.findIndex((word) => STOP.test(word));
    if (cut >= 0) words = words.slice(0, cut);
    while (words.length > 0 && words[words.length - 1].length <= 1) words.pop();
    return words.join(' ');
  };

  const name = parts
    .reverse()
    .map((part) => cleanName(part.replace(new RegExp(`^(?:${CONNECTORS})\\s+`), '')))
    .find((part) => {
      const words = part.split(' ').filter(Boolean);
      if (words.length < 1 || words.length > 6) return false;
      if (words.every((word) => NOT_A_NAME.test(word))) return false;
      return looksLikeName(part);
    });
  if (!name) return null;
  // الاسم يُعرض بعد «عن» فيلزمه الجرّ: «عن أبي هريرة» لا «عن أبو/أبا هريرة».
  // والكنية وحدها هي التي يظهر فيها الإعراب في الرسم.
  // (حدّ الكلمة `\b` لا يعمل مع العربية في JS، فالتحقّق بالمسافة التالية.)
  const genitive = name.replace(/^أب[واً](?=\s)/, 'أبي');
  // «رضي الله عنه» تُذكر في «تراث» برمزٍ لا بنصّ، فنكتبها — ولها تأنيث.
  return `${genitive} رضي الله ${isFeminine(genitive) ? 'عنها' : 'عنه'}`;
}

/**
 * يستخرج متون الصفحة من وسم <hadeeth> تحت باب معلوم، ويلحق بكل متنٍ رقمَه
 * والصحابيَّ الراوي من إسناده. وما لم يتبيّن رقمه يُسقَط، لأن الرقم مفتاح
 * كشف التكرار وقيدٌ فريد في قاعدة البيانات.
 *
 * تُقرأ الصفحة على ترتيبها — عنوانٌ ثم ما تحته — فإن بدأ في وسطها بابٌ آخر
 * انتقل الحكم إليه، فلا يُنسب إلى باب الفضائل ما ليس منه.
 */
export function extractHadiths(pageText, context) {
  const clean = cleanPage(pageText);
  const out = [];
  let { chapter, bab } = context;

  const events = [
    ...[...clean.matchAll(HEADING)].map((m) => ({ index: m.index, ...classifyHeading(m[1]) })),
    ...groupMatns(clean).map((group) => ({ ...group, level: 'matn' })),
  ].sort((a, b) => a.index - b.index);

  for (const event of events) {
    if (event.level === 'chapter') {
      chapter = event.title;
      bab = null;
      continue;
    }
    if (event.level === 'bab') {
      bab = event.title;
      continue;
    }
    if (event.level !== 'matn') continue;

    // بوّابتان معاً: الكتاب في الأعمال، والباب في الفضائل.
    if (!isDeedChapter(chapter) || !isMeritBab(bab)) continue;

    // المتن مكتملٌ في المطبوع: محوطٌ بعلامتَي التنصيص من أوله إلى آخره.
    const quoted = event.body.replace(PAGE_BREAK, ' ').replace(/\s+/g, ' ').trim();
    if (!QUOTED.test(quoted)) continue;

    const isnad = clean.slice(0, event.index);
    // الكلام منسوبٌ إلى النبي ﷺ نصّاً — لا حكايةَ راوٍ ولا قولَ صحابي.
    if (!PROPHET_SPEECH.test(speechForm(isnad))) continue;

    const matn = tidy(quoted);
    if (!isPublishable(matn)) continue;

    // الرقم يسبق الإسناد؛ وبُعدُه عن المتن يكشف أنه لحديثٍ آخر لا لهذا.
    const numbers = [...isnad.matchAll(HADITH_NUMBER)];
    const marker = numbers[numbers.length - 1];
    const number = marker ? positiveInt(toLatinDigits(marker[2])) : null;
    if (!number || event.index - marker.index > ISNAD_WINDOW) continue;

    out.push({ matn, number, chapter, bab, narrator: narratorOf(isnad) });
  }

  return { items: out, context: { chapter, bab } };
}

